export type TimePeriod = 'morning' | 'afternoon' | 'evening' | 'night';

export function getTimeOfDayBucket(date = new Date()): {
  period: TimePeriod;
  greeting: string;
  subtitle: string;
  itemIds: string[];
} {
  const hour = date.getHours();
  if (hour >= 5 && hour < 12) {
    return {
      period: 'morning',
      greeting: 'Good Morning at Bidholi',
      subtitle: 'Freshly brewed Masala Chai paired with warm breakfast bites before your first lecture.',
      itemIds: ['masala-chai', 'bombay-masala-toast', 'cappuccino', 'bun-maska'],
    };
  }
  if (hour >= 12 && hour < 16) {
    return {
      period: 'afternoon',
      greeting: 'Afternoon Campus Refresher',
      subtitle: 'Chilled cold coffee, iced mocha, and crisp grilled sandwiches to beat the midday lull.',
      itemIds: ['cold-coffee', 'paneer-tikka-sandwich', 'iced-mocha', 'peach-iced-tea'],
    };
  }
  if (hour >= 16 && hour < 21) {
    return {
      period: 'evening',
      greeting: 'Golden Hour Chai & Maggi',
      subtitle: 'Steaming kulhad masala chai and gooey Cheese Maggi as the hills cool down.',
      itemIds: ['kulhad-chai', 'cheese-maggi', 'combo-student', 'peri-peri-fries'],
    };
  }
  return {
    period: 'night',
    greeting: 'Late-Night Study Fuel',
    subtitle: 'Rich espresso pours and warm dark chocolate brownies for late-night assignments.',
    itemIds: ['cappuccino', 'chocolate-brownie', 'hazelnut-latte', 'iced-mocha'],
  };
}
