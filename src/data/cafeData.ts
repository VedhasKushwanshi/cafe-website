export function calculateCustomizedPrice(
  basePrice: number,
  customization?: DrinkCustomization
): number {
  if (!customization) return basePrice;
  const sizeDelta = SIZE_OPTIONS.find((s) => s.label === customization.size)?.delta ?? 0;
  const milkDelta = MILK_OPTIONS.find((m) => m.label === customization.milk)?.delta ?? 0;
  const extrasDelta = customization.extras.reduce((sum, extraName) => {
    const match = EXTRAS_OPTIONS.find((e) => e.label === extraName);
    return sum + (match?.delta ?? 0);
  }, 0);
  return Math.max(39, basePrice + sizeDelta + milkDelta + extrasDelta);
}

